def translate_message(message: str) -> str:
    if _LANG == "zh":
        return message
    return _MAPS.get(_LANG, _EN).get(message, message)


def set_language(language: str | None) -> None:
    global _LANG
    code = str(language or "").lower()
    _LANG = code if code in _MAPS or code == "zh" else "en"


def language() -> str:
    return _LANG


def tr(zh: str, en: str) -> str:
    if _LANG == "zh":
        return zh
    return _MAPS.get(_LANG, _EN).get(zh, en)


def translate_widgets(root: QWidget) -> None:
    if _LANG == "zh":
        return
    mapping = _MAPS.get(_LANG, _EN)
    for widget in root.findChildren(QWidget):
        try:
            if isinstance(widget, (QLabel, QAbstractButton)):
                text = widget.text()
                if text in mapping:
                    widget.setText(mapping[text])
            if isinstance(widget, QLineEdit) and widget.placeholderText() in mapping:
                widget.setPlaceholderText(mapping[widget.placeholderText()])
            if widget.toolTip() in mapping:
                widget.setToolTip(mapping[widget.toolTip()])
        except Exception:
            continue
    for tabs in root.findChildren(QTabWidget):
        for index in range(tabs.count()):
            text = tabs.tabText(index)
            if text in mapping:
                tabs.setTabText(index, mapping[text])
    for combo in root.findChildren(QComboBox):
        for index in range(combo.count()):
            text = combo.itemText(index)
            if text in mapping:
                combo.setItemText(index, mapping[text])
